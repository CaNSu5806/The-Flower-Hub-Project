-- =============================================================================
-- The Flower Hub Database: DDL Schema
-- =============================================================================

-- 1. Identity & RBAC
CREATE TABLE Roles (
    role_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE Users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id NUMBER NOT NULL,
    email VARCHAR2(255) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    full_name VARCHAR2(100) NOT NULL,
    phone VARCHAR2(20),
    CONSTRAINT fk_user_role FOREIGN KEY (role_id) REFERENCES Roles(role_id)
);

CREATE TABLE UserAddresses (
    address_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    location VARCHAR2(500) NOT NULL,
    CONSTRAINT fk_address_user FOREIGN KEY (user_id) REFERENCES Users(user_id) ON DELETE CASCADE
);

-- 2. Commerce & Stores
CREATE TABLE Coupons (
    coupon_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR2(50) UNIQUE NOT NULL,
    discount_percent NUMBER(5,2),
    expiry_date DATE NOT NULL,
    is_active NUMBER(1) DEFAULT 1
);

CREATE TABLE Shops (
    shop_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    address VARCHAR2(255),
    rating NUMBER(2,1) CONSTRAINT chk_shops_rating CHECK (rating BETWEEN 0 AND 5),
    owner_id NUMBER,
    is_active NUMBER(1) DEFAULT 1,
    CONSTRAINT fk_shops_owner FOREIGN KEY (owner_id) REFERENCES Users(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_shops_active CHECK (is_active IN (0, 1))
);

CREATE TABLE Categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(100) NOT NULL
);

CREATE TABLE OpeningHours (
    hour_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id NUMBER,
    time_details VARCHAR2(255),
    CONSTRAINT fk_opening_hours_shop FOREIGN KEY (shop_id) REFERENCES Shops(shop_id) ON DELETE CASCADE
);

-- 3. Catalog & Inventory
CREATE TABLE Products (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id NUMBER NOT NULL,
    category_id NUMBER NOT NULL,
    name VARCHAR2(150) NOT NULL,
    price NUMBER(10, 2) NOT NULL,
    stock_quantity NUMBER DEFAULT 0 NOT NULL,
    description VARCHAR2(1000),
    CONSTRAINT chk_products_stock CHECK (stock_quantity >= 0),
    CONSTRAINT chk_products_price CHECK (price > 0),
    CONSTRAINT fk_products_shop FOREIGN KEY (shop_id) REFERENCES Shops(shop_id),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES Categories(category_id)
);

CREATE TABLE ProductExtras (
    extra_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER NOT NULL,
    extra_name VARCHAR2(100) NOT NULL,
    extra_price NUMBER(10, 2) DEFAULT 0.00,
    CONSTRAINT fk_product_extras FOREIGN KEY (product_id) REFERENCES Products(product_id) ON DELETE CASCADE
);

CREATE TABLE InventoryLogs (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER NOT NULL,
    change_amount NUMBER NOT NULL,
    action_type VARCHAR2(50) DEFAULT 'SYSTEM' NOT NULL,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_inventory_logs FOREIGN KEY (product_id) REFERENCES Products(product_id) ON DELETE CASCADE
);

-- 4. Orders, Logistics & Transactions
CREATE TABLE Orders (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 26) PRIMARY KEY,
    customer_id NUMBER NOT NULL,
    shop_id NUMBER NOT NULL,
    courier_id NUMBER,
    coupon_id NUMBER,
    total_price NUMBER(10,2) DEFAULT 0,
    status VARCHAR2(20) DEFAULT 'PENDING',
    order_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ord_cust FOREIGN KEY (customer_id) REFERENCES Users(user_id),
    CONSTRAINT fk_ord_shop FOREIGN KEY (shop_id) REFERENCES Shops(shop_id),
    CONSTRAINT fk_ord_cour FOREIGN KEY (courier_id) REFERENCES Users(user_id),
    CONSTRAINT fk_ord_coup FOREIGN KEY (coupon_id) REFERENCES Coupons(coupon_id)
);

CREATE TABLE OrderDetails (
    detail_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER,
    product_id NUMBER,
    quantity NUMBER NOT NULL CHECK (quantity > 0),
    unit_price NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_ord_det_order FOREIGN KEY (order_id) REFERENCES Orders(order_id) ON DELETE CASCADE,
    CONSTRAINT fk_ord_det_product FOREIGN KEY (product_id) REFERENCES Products(product_id)
);

CREATE TABLE Reviews (
    review_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER NOT NULL,
    customer_id NUMBER NOT NULL,
    rating NUMBER NOT NULL,
    review_text VARCHAR2(4000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_review_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT fk_reviews_order FOREIGN KEY (order_id) REFERENCES Orders(order_id),
    CONSTRAINT fk_reviews_customer FOREIGN KEY (customer_id) REFERENCES Users(user_id)
);

CREATE TABLE Payments (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER NOT NULL,
    payment_method VARCHAR2(50) NOT NULL,
    payment_status VARCHAR2(50) DEFAULT 'Pending',
    transaction_id VARCHAR2(100) UNIQUE,
    payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES Orders(order_id) ON DELETE CASCADE
);
